# Fills {COURSE_LIST} in the prompt with current course titles and codes from the DB.
# NOTE: this runs once, when the agent is created, so restart the app after changing courses.
def build_system_prompt():
    # Fetch every course code and title in order.
    rows = run("SELECT code, title FROM courses ORDER BY semester, id")

    # Turn the rows into a "- title (کد: code)" bullet list so the model can read codes directly.
    course_list = "\n".join(f"- {r['title']} (کد: {r['code']})" for r in rows)

    # Swap the placeholder for the real list and return the finished prompt.
    return PROMPT_TEMPLATE.replace("{COURSE_LIST}", course_list)

# Fills {COURSE_LIST} in the prompt with current course titles from the DB.
def build_system_prompt():
    # Fetch every course title in order.
    rows = run("SELECT title FROM courses ORDER BY semester, id")

    # Turn the rows into a "- title" bullet list.
    course_list = "\n".join(f"- {r['title']}" for r in rows)

    # Swap the placeholder for the real list and return the finished prompt.
    return PROMPT_TEMPLATE.replace("{COURSE_LIST}", course_list)
